/// `ant-schematron/test/schemas/test-message.sch` is not a compile-coverage fixture at all: it is
/// the Schematron Ant task's own negative test case. Its source annotates the lone unnamed
/// `<rule>` with the comment `<!-- NO CONTEXT ATTRIBUTE! -->` and deliberately omits the
/// `@context` the Schematron spec requires, so that the Ant task's own test harness (outside this
/// repository) can assert that its reader reports the missing attribute. It is not meant to
/// compile as a schema on its own.
const MISSING_CONTEXT_ALLOWLIST: &[(&str, &str)] = &[(
    "trunk/ant-schematron/test/schemas/test-message.sch",
    "deliberate negative fixture: its lone <rule> has no @context on purpose (see the \"NO \
     CONTEXT ATTRIBUTE!\" comment in the source)",
)];

/// Runs the reference-suite compile-coverage check.
#[must_use]
pub fn run() -> Vec<SuiteReport> {
    let Some(suite_dir) = env::xml_suite_subdir("schematron", "") else {
        return vec![SuiteReport::unavailable(
            SUITE,
            match env::xml_suites_dir() {
                None => env::missing(env::XML_SUITES_DIR_VAR),
                Some(_) => env::not_found(env::XML_SUITES_DIR_VAR, "schematron/"),
            },
        )];
    };

    let mut files = Vec::new();
    discover_sch_files(&suite_dir, &mut files);
    files.sort();

    let allowlist: BTreeMap<&str, &str> = DANGLING_EXTENDS_ALLOWLIST
        .iter()
        .chain(NON_ATOMIC_CASTABLE_ALLOWLIST)
        .chain(MISSING_CONTEXT_ALLOWLIST)
        .copied()
        .collect();

    let mut report = SuiteReport::new(SUITE);
    for path in &files {
        let id = path
            .strip_prefix(&suite_dir)
            .unwrap_or(path)
            .display()
            .to_string();
        let Ok(text) = fs::read_to_string(path) else {
            report.record_skip("unreadable (not UTF-8)");
            continue;
        };
        if let Some(reason) = allowlist.get(id.as_str()) {
            report.record_skip(format!("documented suite-fixture defect: {reason}"));
            continue;
        }
        match Schematron::compile(&text, None) {
            Ok(_) => report.record_pass(),
            Err(SchematronError::NotASchema { .. }) => {
                report.record_skip("not a standalone sch:schema document");
            }
            Err(error) => report.record_fail(id, error.to_string()),
        }
    }
    vec![report]
}

/// Recursively collects every `.sch` file under `root`, skipping dotfiles/dot-directories such
/// as `.git`.
fn discover_sch_files(root: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(root) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = path.file_name().and_then(OsStr::to_str).unwrap_or_default();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            discover_sch_files(&path, out);
        } else if path.extension().and_then(OsStr::to_str) == Some("sch") {
            out.push(path);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn allowlists_cover_exactly_the_recon_verified_defect_set_without_overlap() {
        let all: Vec<&str> = DANGLING_EXTENDS_ALLOWLIST
            .iter()
            .chain(NON_ATOMIC_CASTABLE_ALLOWLIST)
            .chain(MISSING_CONTEXT_ALLOWLIST)
            .map(|(id, _)| *id)
            .collect();
        // 24 dangling-`sch:extends` fixtures + 13 non-atomic-`castable as` fixtures + 1 deliberate
        // ant-schematron negative fixture, matching the recon-measured 38 schematron failures this
        // allowlist accounts for.
        assert_eq!(
            all.len(),
            38,
            "the three schematron allowlists together should list exactly the 38 documented \
             suite-fixture defects"
        );
        let unique: std::collections::BTreeSet<&str> = all.iter().copied().collect();
        assert_eq!(
            unique.len(),
            all.len(),
            "an id appears in more than one allowlist bucket"
        );
    }

    #[test]
    fn discovers_sch_files_recursively_and_skips_dotdirs() {
        let dir = std::env::temp_dir().join(format!(
            "oxixml-testsuite-schematron-test-{}",
            std::process::id()
        ));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(dir.join("nested")).expect("scratch dir");
        fs::create_dir_all(dir.join(".git")).expect("scratch dir");
        fs::write(dir.join("a.sch"), b"<schema/>").expect("scratch file");
        fs::write(dir.join("nested").join("b.sch"), b"<schema/>").expect("scratch file");
        fs::write(dir.join(".git").join("c.sch"), b"<schema/>").expect("scratch file");
        fs::write(dir.join("d.xml"), b"<schema/>").expect("scratch file");

        let mut found = Vec::new();
        discover_sch_files(&dir, &mut found);
        found.sort();
        assert_eq!(
            found,
            vec![dir.join("a.sch"), dir.join("nested").join("b.sch")]
        );

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn unavailable_when_env_is_unset() {
        // `OXIXML_XML_SUITES_DIR` is not set in the unit-test environment (the suite-driven
        // tests that require it live behind `#[ignore]`; see `tests/`).
        if std::env::var_os(env::XML_SUITES_DIR_VAR).is_some() {
            return;
        }
        let reports = run();
        assert_eq!(reports.len(), 1);
        assert!(!reports[0].is_available());
    }
}
