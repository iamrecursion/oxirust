//! Schematron reference-suite compile-coverage runner.
//!
//! The [Schematron reference implementation]'s own test corpus is fixtures for a build tool, not
//! a pass/fail conformance suite with an expected-output oracle: there is no manifest naming
//! which `.sch` files must compile. What this runner reports instead is *compile coverage* — of
//! every `.sch` file discovered under `$OXIXML_XML_SUITES_DIR/schematron`, how many are
//! standalone `sch:schema` documents that compile under [`Schematron::compile`], how many are
//! fragments meant only for `sch:include` (reported as skipped, not failed — they are not a
//! standalone schema by design), and how many fail to compile.
//!
//! A further, documented set of fixtures is skipped rather than failed even though it *is*
//! meant to be a standalone schema: `DANGLING_EXTENDS_ALLOWLIST`, `NON_ATOMIC_CASTABLE_ALLOWLIST`
//! and `MISSING_CONTEXT_ALLOWLIST` each name a defect in the fixture itself (a dangling
//! `sch:extends`, a `castable as` naming a non-atomic ur-type, or a deliberate negative test of
//! the Schematron Ant task), not in this crate — mirroring the `NOT_WF_ALLOWLIST` pattern
//! [`crate::xmlconf`] uses for the W3C XML suite's own known-divergent cases.
//!
//! [Schematron reference implementation]: https://github.com/Schematron/schematron

