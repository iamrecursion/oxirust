//! Coefficient table for the truncated IAU `2000A_R06` nutation model
//! implemented in [`super::nutation`].
//!
//! **This is not the IAU 2000B series.** It is an independent truncation
//! of the full IAU `2000A_R06` series that reaches the accuracy class
//! ("1 mas") of the IAU 2000B model of McCarthy & Luzum (2003), but its
//! term selection and coefficients differ from that paper's 77-term
//! table; see the provenance note below for why.
//!
//! # Provenance (clean room)
//!
//! This table is a truncation of the full IAU `2000A_R06` nutation series as
//! published by the IERS Conventions Centre in the electronic tables
//! `tab5.3a.txt` (nutation in longitude) and `tab5.3b.txt` (nutation in
//! obliquity) accompanying IERS Conventions (2010), TN36, chapter 5
//! (<https://iers-conventions.obspm.fr/content/chapter5/additional_info/>).
//! Series form: TN36 eq. (5.35); the coefficients here are the `A_i`,
//! `A'_i`, `A''_i`, `A'''_i` (longitude) and `B_i`, `B'_i`, `B''_i`,
//! `B'''_i` (obliquity) of that equation, in microarcseconds (µas) and
//! µas per Julian century.
//!
//! The *concept* of an abridged, sub-milliarcsecond nutation model with a
//! constant "planetary bias" follows McCarthy & Luzum (2003), Celest.
//! Mech. Dyn. Astron. 85, 37 (the IAU 2000B model). The verbatim 77-term
//! IAU 2000B table of that paper is not reproduced in any of the sources
//! this project is permitted to read (the paper itself is paywalled and
//! the public re-publications found are all SOFA-derived source code,
//! which is off limits under the clean-room policy), so this table was
//! regenerated *from the IERS TN36 data* instead, as follows:
//!
//! - **Luni-solar terms** ([`LS_TERMS`], 143 terms): every term of
//!   `tab5.3a.txt`/`tab5.3b.txt` whose planetary multipliers are all zero
//!   and whose selection metric `max(|A_i|, 2 |B_i|)` is `>= 30` µas,
//!   with its full in-phase/out-of-phase coefficients and their time
//!   variations. (The factor 2 makes the metric roughly isotropic in the
//!   two celestial-pole components, since `|B| ~ |A| sin(eps)` for most
//!   terms.)
//! - **Planetary terms** ([`PL_TERMS`], 11 terms): every term with a
//!   non-zero planetary multiplier and metric `>= 50` µas. None of these
//!   carries a time variation in the IERS tables.
//! - **Planetary bias** ([`BIAS_DPSI_UAS`], [`BIAS_DEPS_UAS`]): the mean
//!   of (full series − truncated series) over 1995–2050, sampled monthly
//!   (661 samples, `t = -0.05 + k/1200`, `k = 0..=660`), following the
//!   McCarthy & Luzum (2003) bias approach.
//!
//! Against the full IAU `2000A_R06` series the truncation deviates by at
//! most 0.64 mas in `dpsi` and 0.35 mas in `deps` over 1995–2050, and at
//! most 1.03 mas / 0.38 mas over 1900–2100 (monthly sampling) — the same
//! accuracy class as IAU 2000B ("1 mas", McCarthy & Luzum 2003). The
//! integration test `nutation_oracle.rs` re-derives the full series from
//! the IERS files and enforces those bounds.
//!
//! Generated from the IERS files by a throwaway script (see the module
//! constants for the exact selection rule); regenerate by re-running the
//! selection against `data/iers/tab5.3a.txt` / `tab5.3b.txt`.

/// Luni-solar term: `([l, l', F, D, Om] multipliers, [ps, pst, psc, psct,
/// ec, ect, es, est])` where, with `arg` the argument formed on the
/// Delaunay variables and `t` in Julian centuries TT:
///
/// ```text
/// dpsi += (ps + pst*t) * sin(arg) + (psc + psct*t) * cos(arg)   [µas]
/// deps += (ec + ect*t) * cos(arg) + (es + est*t) * sin(arg)     [µas]
/// ```
pub(crate) type LsTerm = ([i8; 5], [f64; 8]);

/// Planetary term: `([l, l', F, D, Om, L_Me, L_Ve, L_E, L_Ma, L_J, L_Sa,
/// L_U, L_Ne, p_A] multipliers, [ps, psc, ec, es])`:
///
/// ```text
/// dpsi += ps * sin(arg) + psc * cos(arg)   [µas]
/// deps += ec * cos(arg) + es * sin(arg)    [µas]
/// ```
pub(crate) type PlTerm = ([i8; 14], [f64; 4]);

