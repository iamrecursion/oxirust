"""Real Feynman-100 recovery runner (M6, PySR side).

Consumes the same per-equation CSVs that the phop `feynman` bin uses (generated by
`gen_feynman.py`; last column = target), runs PySR on each with a rich operator set and a
per-equation time budget, and records R^2 + wall-clock + recovered-flag + best equation.
Output: incremental per-line progress + a JSON file.

Usage:
    python3 pysr_feynman.py <csv_dir> <out_json> [timeout_s]
"""
import glob, json, os, sys, time
import numpy as np
from pysr import PySRRegressor

R2_TOL = 0.999

def r2(y, p):
    ss_res = float(np.sum((y - p) ** 2))
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    return 1.0 - ss_res / ss_tot if ss_tot != 0 else float("nan")

def make_model(timeout_s):
    return PySRRegressor(
        niterations=40,
        maxsize=30,
        timeout_in_seconds=timeout_s,
        binary_operators=["+", "-", "*", "/"],
        unary_operators=["exp", "log", "sqrt", "sin", "cos", "tan", "asin", "tanh",
                         "square", "cube"],
        progress=False,
        verbosity=0,
        temp_equation_file=True,
    )

def main():
    csv_dir = sys.argv[1] if len(sys.argv) > 1 else "feynman_data"
    out_json = sys.argv[2] if len(sys.argv) > 2 else "pysr_feynman.json"
    timeout_s = int(sys.argv[3]) if len(sys.argv) > 3 else 40

    files = sorted(glob.glob(os.path.join(csv_dir, "*.csv")))
    # Warm up the Julia backend once (not timed).
    _x = np.random.default_rng(0).uniform(0, 1, size=(40, 1))
    make_model(5).fit(_x, _x.ravel())

    results = {}
    rec = 0
    for i, f in enumerate(files):
        name = os.path.splitext(os.path.basename(f))[0]
        data = np.loadtxt(f, delimiter=",", skiprows=1)
        if data.ndim == 1:
            data = data.reshape(-1, 1)
        X, y = data[:, :-1], data[:, -1]
        try:
            m = make_model(timeout_s)
            t0 = time.time()
            m.fit(X, y)
            dt = time.time() - t0
            pred = m.predict(X)
            score = r2(y, pred)
            eq = str(m.get_best()["equation"])
        except Exception as e:
            dt, score, eq = float("nan"), float("nan"), f"ERROR: {e}"
        is_rec = bool(np.isfinite(score) and score >= R2_TOL)
        rec += int(is_rec)
        results[name] = {"r2": score, "time_s": dt, "recovered": is_rec, "eq": eq}
        print(f"[{i+1}/{len(files)}] {name:24s} r2={score:.4f} t={dt:6.1f}s rec={is_rec}",
              flush=True)
        json.dump(results, open(out_json, "w"), indent=1)  # checkpoint each step

    print(f"PySR feynman: recovered {rec}/{len(files)} (R2 >= {R2_TOL})")

if __name__ == "__main__":
    main()
