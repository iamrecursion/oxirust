/// Parameter `t` in `[0, 1]` of the zero crossing between two densities of
/// opposite sign, `t = (0 - d_lo) / (d_hi - d_lo)`.
///
/// Falls back to the midpoint if the quotient is not finite (infinite or NaN
/// densities), so a crossing point is always on its edge.
fn crossing_parameter(d_lo: f64, d_hi: f64) -> f64 {
    let t = -d_lo / (d_hi - d_lo);
    if t.is_finite() {
        t.clamp(0.0, 1.0)
    } else {
        0.5
    }
}

/// Extract the `density = 0` isosurface of `terrain` as a triangle soup.
///
/// A sample is solid when its density is `>= 0` and empty when it is negative.
/// The samples sit at the lattice points `origin + (i, j, k) * voxel_size`.
/// Triangles wind counter-clockwise when seen from the empty side, so their
/// right-hand normals point out of the solid.  Terrains with fewer than two
/// samples along an axis, a non-positive or non-finite voxel size, or a density
/// array that does not match the dimensions have no surface.
pub(super) fn extract_isosurface(terrain: &VoxelTerrain) -> Vec<[[f64; 3]; 3]> {
    let (nx, ny, nz) = (terrain.nx, terrain.ny, terrain.nz);
    let voxel_size = terrain.voxel_size;
    let mut triangles = Vec::new();
    if nx < 2 || ny < 2 || nz < 2 || !voxel_size.is_finite() || voxel_size <= 0.0 {
        return triangles;
    }
    if terrain.densities.len() != nx * ny * nz {
        return triangles;
    }
    let lattice_point = |i: usize, j: usize, k: usize| -> [f64; 3] {
        [
            terrain.origin[0] + i as f64 * voxel_size,
            terrain.origin[1] + j as f64 * voxel_size,
            terrain.origin[2] + k as f64 * voxel_size,
        ]
    };

    for iz in 0..nz - 1 {
        for iy in 0..ny - 1 {
            for ix in 0..nx - 1 {
                let mut densities = [0.0_f64; 8];
                let mut case = 0usize;
                for (corner, offset) in MC_CORNER_OFFSETS.iter().enumerate() {
                    let index = (ix + offset[0]) + nx * ((iy + offset[1]) + ny * (iz + offset[2]));
                    let density = terrain.densities[index];
                    densities[corner] = density;
                    if density < 0.0 {
                        case |= 1 << corner;
                    }
                }
                let crossed = MC_EDGE_TABLE[case];
                if crossed == 0 {
                    continue;
                }

                let mut points = [[0.0_f64; 3]; 12];
                for (edge, point) in points.iter_mut().enumerate() {
                    if crossed & (1 << edge) == 0 {
                        continue;
                    }
                    let [lo, hi] = MC_EDGE_ASCENDING[edge];
                    let (lo_offset, hi_offset) = (MC_CORNER_OFFSETS[lo], MC_CORNER_OFFSETS[hi]);
                    let p_lo =
                        lattice_point(ix + lo_offset[0], iy + lo_offset[1], iz + lo_offset[2]);
                    let p_hi =
                        lattice_point(ix + hi_offset[0], iy + hi_offset[1], iz + hi_offset[2]);
                    let t = crossing_parameter(densities[lo], densities[hi]);
                    *point = [
                        p_lo[0] + t * (p_hi[0] - p_lo[0]),
                        p_lo[1] + t * (p_hi[1] - p_lo[1]),
                        p_lo[2] + t * (p_hi[2] - p_lo[2]),
                    ];
                }

                for row in MC_TRI_TABLE[case].chunks_exact(3) {
                    let (Ok(a), Ok(b), Ok(c)) = (
                        usize::try_from(row[0]),
                        usize::try_from(row[1]),
                        usize::try_from(row[2]),
                    ) else {
                        break;
                    };
                    let triangle = [points[a], points[b], points[c]];
                    // A sample whose density is exactly zero puts the crossing of
                    // every incident edge on the sample itself; the triangles that
                    // join such coincident crossings have no area.  Dropping them
                    // keeps the surface closed (their sides cancel pairwise).
                    if triangle[0] == triangle[1]
                        || triangle[1] == triangle[2]
                        || triangle[0] == triangle[2]
                    {
                        continue;
                    }
                    triangles.push(triangle);
                }
            }
        }
    }
    triangles
}
